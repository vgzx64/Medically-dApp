#!/usr/bin/env bash
# Start a local Anvil node, deploy the registry and grant the registrar role.
#
#   ./tools/localnet.sh start     - start Anvil in the background
#   ./tools/localnet.sh deploy    - deploy the contract
#   ./tools/localnet.sh stop      - stop Anvil
#   ./tools/localnet.sh status    - show the state
#
# Environment:
#   ANVIL_PORT   (default 8545)
#   ANVIL_KEY    (default Anvil test key #0)

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ANVIL_PORT="${ANVIL_PORT:-8545}"
ANVIL_KEY="${ANVIL_KEY:-0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80}"
PID_FILE="$ROOT/.anvil.pid"
LOG_FILE="$ROOT/artifacts/logs/anvil.log"

# The admin and the registrar are the first two Anvil accounts.
ADMIN_KEY="$ANVIL_KEY"
REGISTRAR_KEY="0x59c6995e998f97a5a0044966f0945389dc9e86dae88c7a8412f4603b6b78690d"
REGISTRAR_ADDR="0x70997970C51812dc3A010C7d01b50e0d17dc79C8"
ADMIN_ADDR="0xf39Fd6e51aad88F6F4ce6aB8827279cffFb92266"

FOUNDRY_BIN="${FOUNDRY_BIN:-$HOME/.foundry/bin}"
export PATH="$FOUNDRY_BIN:$PATH"

start() {
  if [ -f "$PID_FILE" ] && kill -0 "$(cat "$PID_FILE")" 2>/dev/null; then
    echo "Anvil is already running (pid $(cat "$PID_FILE"))"
    return 0
  fi
  mkdir -p "$(dirname "$LOG_FILE")"
  nohup anvil --port "$ANVIL_PORT" --host 127.0.0.1 \
    --chain-id 31337 --block-base-fee-per-gas 0 \
    > "$LOG_FILE" 2>&1 &
  echo $! > "$PID_FILE"
  sleep 2
  echo "Anvil started on http://127.0.0.1:$ANVIL_PORT (pid $(cat "$PID_FILE"))"
}

stop() {
  if [ -f "$PID_FILE" ]; then
    kill "$(cat "$PID_FILE")" 2>/dev/null || true
    rm -f "$PID_FILE"
    echo "Anvil stopped"
  else
    echo "Anvil is not running"
  fi
}

status() {
  if [ -f "$PID_FILE" ] && kill -0 "$(cat "$PID_FILE")" 2>/dev/null; then
    echo "Anvil is running (pid $(cat "$PID_FILE"))"
  else
    echo "Anvil is NOT running"
  fi
  if [ -f "$ROOT/.contract-address" ]; then
    echo "Contract: $(cat "$ROOT/.contract-address")"
  fi
}

deploy() {
  export ADMIN_PRIVATE_KEY="$ADMIN_KEY"
  export REGISTRAR_ADDRESS="$REGISTRAR_ADDR"
  cd "$ROOT"
  forge script script/Deploy.s.sol:Deploy \
    --rpc-url "http://127.0.0.1:$ANVIL_PORT" \
    --broadcast --private-key "$ADMIN_KEY" \
    --skip-simulation > /dev/null
  # The address is taken from the broadcast artefact.
  local addr
  addr="$(python3 - <<'PY'
import json, glob, os
best = None
for f in glob.glob('broadcast/Deploy.s.sol/31337/run-latest.json'):
    d = json.load(open(f))
    for tx in d.get('transactions', []):
        if tx.get('transactionType') == 'CREATE':
            best = tx.get('contractAddress')
print(best or '')
PY
)"
  if [ -z "$addr" ]; then
    echo "Could not determine the contract address" >&2
    exit 1
  fi
  echo "$addr" > "$ROOT/.contract-address"
  echo "Contract deployed at $addr"
  echo "Registrar: $REGISTRAR_ADDR"

  # The built-in dev wallet (Anvil account #0) is granted the registrar role
  # as well, so that the dApp can be demonstrated without MetaMask.
  REGISTRY_ADDRESS="$addr" \
  REGISTRAR_ADDRESS="$ADMIN_ADDR" \
  ENABLED=true \
  forge script script/GrantRoles.s.sol:GrantRoles \
    --rpc-url "http://127.0.0.1:$ANVIL_PORT" \
    --broadcast --private-key "$ADMIN_KEY" \
    --skip-simulation > /dev/null
  echo "Dev wallet registrar: $ADMIN_ADDR"

  # Vite reads client/.env*, not the repository root: generate the client
  # environment so that `npm --prefix client run dev` works out of the box.
  local env_file="$ROOT/client/.env.local"
  cat > "$env_file" <<ENV
# Generated by tools/localnet.sh deploy — do not edit by hand.
VITE_RPC_URL=http://127.0.0.1:$ANVIL_PORT
VITE_CHAIN_ID=31337
VITE_WALLET_MODE=dev
VITE_DEV_PRIVATE_KEY=$ADMIN_KEY
VITE_CONTRACT_ADDRESS=$addr
VITE_REGISTRAR_ADDRESS=$ADMIN_ADDR
ENV
  echo "Client environment written to $env_file"
}

case "${1:-}" in
  start) start ;;
  stop) stop ;;
  status) status ;;
  deploy) deploy ;;
  *)
    echo "Usage: $0 {start|stop|status|deploy}" >&2
    exit 2
    ;;
esac
